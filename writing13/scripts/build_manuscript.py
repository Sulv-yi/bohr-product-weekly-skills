#!/usr/bin/env python3
"""按案例要求生成结构完整、可直接编译的 .tex 成稿骨架。

用法:
    python3 build_manuscript.py --case /input/case.json --out /app/output
    python3 build_manuscript.py --out /app/output --sections "Introduction,Method,Results"
    python3 build_manuscript.py --out /app/work --template ieeetran --main paper.tex

作用：把"从零搭一份符合模板、能编译、章节齐全的稿件"这一步变成确定性动作，
避免 agent 只产出检查报告而交不出可编辑 .tex 成稿。

生成物：
  <main>.tex   完整骨架：导言区 + 摘要 + 各章节 + 公式/表格锚点 + 参考文献
  refs.bib     参考文献条目骨架
  manuscript_plan.json  章节清单与写作要求（供后续逐节填充与自检）

注意：骨架里的章节正文是**空的**，只带 LaTeX 注释形式的写作要求。
空骨架不算成稿，必须用 check_manuscript.py 过关才算交付。
"""
import argparse
import json
import os
import re
import sys

DEFAULT_SECTIONS = [
    ("Introduction", "说明研究问题、为什么重要、已有工作缺口、本文贡献。"),
    ("Related Work", "按技术路线分组评述，指出各组与本文的差别，不逐篇罗列。"),
    ("Method", "给出形式化设定、关键公式与符号定义，公式须带编号并在正文引用。"),
    ("Experiments", "写清数据、基线、指标、超参与重复次数，保证他人可复现。"),
    ("Results", "用表格或图给出结果，配数值与统计口径，与基线同预算对比。"),
    ("Discussion", "解释结果成因、适用边界与失败情形，不夸大结论。"),
    ("Conclusion", "回收贡献，给出限制与后续方向。"),
]

# 模板名 -> documentclass 选项
TEMPLATE_CLASS = {
    "article": r"\documentclass[11pt]{article}",
    "ieeetran": r"\documentclass[journal]{IEEEtran}",
    "ieee": r"\documentclass[journal]{IEEEtran}",
    "acmart": r"\documentclass[sigconf]{acmart}",
    "elsarticle": r"\documentclass[preprint,12pt]{elsarticle}",
    "revtex": r"\documentclass[aps,prl,twocolumn]{revtex4-2}",
    "lncs": r"\documentclass[runningheads]{llncs}",
}


def norm_sections(raw):
    """把多种形态的章节声明归一为 [(title, hint), ...]。"""
    out = []
    if not raw:
        return out
    if isinstance(raw, str):
        raw = [s for s in re.split(r'[,;、\n]+', raw) if s.strip()]
    for item in raw:
        if isinstance(item, str):
            t = item.strip()
            if t:
                out.append((t, ""))
        elif isinstance(item, dict):
            t = str(item.get("title") or item.get("name") or item.get("section") or "").strip()
            if t:
                out.append((t, str(item.get("hint") or item.get("requirement") or "")))
    return out


def pick_sections(case, cli_sections):
    if cli_sections:
        got = norm_sections(cli_sections)
        if got:
            return got
    if isinstance(case, dict):
        for key in ("required_sections", "sections", "manuscript_sections", "outline"):
            got = norm_sections(case.get(key))
            if got:
                return got
    return list(DEFAULT_SECTIONS)


def slug(title):
    s = re.sub(r'[^A-Za-z0-9]+', '-', title).strip('-').lower()
    return s or 'sec'


def build(case, sections, main_name, template, title, author, bib_name):
    cls = TEMPLATE_CLASS.get((template or "article").lower(), TEMPLATE_CLASS["article"])
    if template and template.lower().endswith(".cls"):
        cls = r"\documentclass{%s}" % os.path.splitext(os.path.basename(template))[0]

    L = []
    L.append("% Generated by build_manuscript.py — 结构骨架，正文需按材料逐节写实")
    L.append(cls)
    L.append(r"\usepackage[utf8]{inputenc}")
    L.append(r"\usepackage[T1]{fontenc}")
    L.append(r"\usepackage{amsmath,amssymb}")
    L.append(r"\usepackage{booktabs}")
    L.append(r"\usepackage{graphicx}")
    L.append(r"\usepackage{hyperref}")
    L.append("")
    L.append(r"\title{%s}" % title)
    L.append(r"\author{%s}" % author)
    L.append(r"\date{\today}")
    L.append("")
    L.append(r"\begin{document}")
    L.append(r"\maketitle")
    L.append("")
    L.append(r"\begin{abstract}")
    L.append("% 写作要求：3-5 句，覆盖问题、做法、主要结果（带数值）、结论；不引用文献、不出现图表编号。")
    L.append(r"\end{abstract}")
    L.append("")

    # 主公式锚点放在方法类章节；没有方法类章节时退到第二节
    def _is_method(t):
        low = t.lower()
        return any(k in low for k in ('method', 'approach', 'model', 'formulation')) or '方法' in t

    method_idx = next((i for i, (t, _) in enumerate(sections, 1) if _is_method(t)), None)
    if method_idx is None:
        method_idx = 2 if len(sections) >= 2 else 1

    for idx, (sec_title, hint) in enumerate(sections, 1):
        lab = "sec:" + slug(sec_title)
        L.append(r"\section{%s}\label{%s}" % (sec_title, lab))
        L.append("%% 写作要求：%s" % (hint or "按材料写实，关键论断标注来源。"))
        L.append("%% 本节正文待写：写完须达到实质篇幅（默认 >=120 字），否则 check_manuscript 不通过。")
        L.append("")
        # 在方法类章节插入公式锚点，保证成稿具备可核验的数学要素
        low = sec_title.lower()
        if idx == method_idx:
            L.append(r"\begin{equation}")
            L.append(r"  % 填入材料中的主公式，符号须在正文定义")
            L.append(r"  \label{eq:main}")
            L.append(r"\end{equation}")
            L.append("")
        if "result" in low or "experiment" in low or "结果" in sec_title or "实验" in sec_title:
            L.append(r"\begin{table}[t]")
            L.append(r"  \centering")
            L.append(r"  \caption{主结果对照（数值须来自实际运行或材料，注明统计口径）}")
            L.append(r"  \label{tab:main}")
            L.append(r"  \begin{tabular}{lcc}")
            L.append(r"    \toprule")
            L.append(r"    Method & Metric & Value \\")
            L.append(r"    \midrule")
            L.append(r"    % 每条基线一行，数值与单位须与材料一致")
            L.append(r"    \bottomrule")
            L.append(r"  \end{tabular}")
            L.append(r"\end{table}")
            L.append("")

    L.append(r"\bibliographystyle{plain}")
    L.append(r"\bibliography{%s}" % bib_name)
    L.append("")
    L.append(r"\end{document}")
    tex = "\n".join(L) + "\n"

    bib = (
        "% Generated by build_manuscript.py — 参考文献骨架\n"
        "% 每条须来自材料中真实出现的文献；不得编造条目。\n"
        "% 示例（取消注释后填入真实信息）：\n"
        "% @article{key2024,\n"
        "%   author = {Last, First and Other, Author},\n"
        "%   title  = {Real Title From Material},\n"
        "%   journal= {Journal Name},\n"
        "%   year   = {2024},\n"
        "%   volume = {1}, pages = {1--10}\n"
        "% }\n"
    )
    plan = {
        "main_file": main_name,
        "bib_file": bib_name,
        "template": template or "article",
        "sections": [{"index": i, "title": t, "label": "sec:" + slug(t), "hint": h}
                     for i, (t, h) in enumerate(sections, 1)],
        "gate": "空骨架不是成稿：逐节写实后运行 check_manuscript.py 通过才算交付",
    }
    return tex, bib, plan


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case")
    ap.add_argument("--out", default="/app/output")
    ap.add_argument("--main", default="main.tex")
    ap.add_argument("--bib", default="refs")
    ap.add_argument("--template")
    ap.add_argument("--title")
    ap.add_argument("--author")
    ap.add_argument("--sections")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    case = {}
    if args.case and os.path.isfile(args.case):
        case = json.load(open(args.case, encoding="utf-8"))

    os.makedirs(args.out, exist_ok=True)
    tex_path = os.path.join(args.out, args.main)
    bib_path = os.path.join(args.out, args.bib + ".bib")
    plan_path = os.path.join(args.out, "manuscript_plan.json")

    # 已存在非空成稿时不覆盖，避免把agent已写的正文冲掉
    if os.path.isfile(tex_path) and not args.force:
        body = open(tex_path, encoding="utf-8", errors="replace").read()
        if len(body) > 400 and "本节正文待写" not in body:
            print(json.dumps({"status": "skipped", "reason": "已存在成稿，未覆盖（需要重建请加 --force）",
                              "tex": tex_path}, ensure_ascii=False))
            return 0

    sections = pick_sections(case, args.sections)
    title = args.title or (case.get("title") if isinstance(case, dict) else None) or "Manuscript"
    author = args.author or (case.get("author") if isinstance(case, dict) else None) or "Author"
    template = args.template or (case.get("template") if isinstance(case, dict) else None) or "article"

    tex, bib, plan = build(case, sections, args.main, template, title, author, args.bib)
    open(tex_path, "w", encoding="utf-8").write(tex)
    if not os.path.exists(bib_path):
        open(bib_path, "w", encoding="utf-8").write(bib)
    open(plan_path, "w", encoding="utf-8").write(json.dumps(plan, ensure_ascii=False, indent=2))

    print(json.dumps({
        "status": "built",
        "tex": tex_path,
        "bib": bib_path,
        "plan": plan_path,
        "section_count": len(sections),
        "sections": [s["title"] for s in plan["sections"]],
        "next": "按 manuscript_plan.json 逐节写实，然后 python3 check_manuscript.py %s" % tex_path,
    }, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
